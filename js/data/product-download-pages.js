function escapeProductDownloadHtml(text) {
    return String(text)
        .replace(/&/g, "&amp;")
        .replace(/</g, "&lt;")
        .replace(/>/g, "&gt;")
        .replace(/"/g, "&quot;")
        .replace(/'/g, "&#39;");
}

function getCurrentProductDownloadKey() {
    var path = window.location.pathname.replace(/\\/g, "/");
    var match = path.match(/\/pages\/dream7c-([A-Za-z0-9]+)\//i);
    return match ? match[1].toUpperCase() : "";
}

function formatChangelogTitle(title) {
    return escapeProductDownloadHtml(title).replace(/ /g, "&nbsp;");
}

