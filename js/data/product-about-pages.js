function escapeProductAboutHtml(text) {
    return String(text)
        .replace(/&/g, "&amp;")
        .replace(/</g, "&lt;")
        .replace(/>/g, "&gt;")
        .replace(/"/g, "&quot;")
        .replace(/'/g, "&#39;");
}

function getCurrentProductAboutKey() {
    var path = window.location.pathname.replace(/\\/g, "/");
    var match = path.match(/\/pages\/dream7c-([A-Za-z0-9]+)\//i);
    return match ? match[1].toUpperCase() : "";
}

function renderProductAboutPage() {
    var key = getCurrentProductAboutKey();
    var data = productAboutPageData[key];
    var title;
    var intro;
    var history;
    var developers;
    var i;
    var introHtml;
    var historyHtml;
    var developersHtml;

    if (!data) {
        return;
    }

    title = document.getElementById("product-about-title");
    intro = document.getElementById("i1");
    history = document.getElementById("i2");
    developers = document.getElementById("i3");

    if (title) {
        title.textContent = data.title;
        document.title = data.title;
    }

    if (intro) {
        introHtml = escapeProductAboutHtml(data.intro).replace(/\n\n/g, "<br/><br/>").replace(/\n/g, "<br/>");
        intro.innerHTML = '<p class="tx2v">简介</p><p class="tx3">&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;' + introHtml + "</p>";
    }

    if (history) {
        historyHtml = "";
        for (i = 0; i < data.history.length; i++) {
            historyHtml += escapeProductAboutHtml(data.history[i]) + "<br/>";
        }
        history.innerHTML = '<p class="tx2v">历史信息</p><p class="tx3" style="line-height:30px;">' + historyHtml + "</p>";
    }

    if (developers) {
        developersHtml = "";
        for (i = 0; i < data.developers.length; i++) {
            developersHtml += escapeProductAboutHtml(data.developers[i]) + "<br/>";
        }
        developers.innerHTML = '<p class="tx2v">开发人员</p><p class="tx3" style="line-height:30px;">' + developersHtml + "</p>";
    }
}
