function escapeAboutHtml(text) {
    return String(text)
        .replace(/&/g, "&amp;")
        .replace(/</g, "&lt;")
        .replace(/>/g, "&gt;")
        .replace(/"/g, "&quot;")
        .replace(/'/g, "&#39;");
}

function renderAboutProductList(selector) {
    var container = document.querySelector(selector);
    var html = "";
    var i;
    var item;
    var j;

    if (!container) {
        return;
    }

    for (i = 0; i < aboutProductItems.length; i++) {
        item = aboutProductItems[i];
        html += '<a href="' + escapeAboutHtml(item.href) + '"><div style="cursor:pointer;clear:both;">';
        html += '<div class="diva1n"><img src="' + escapeAboutHtml(item.logoSrc) + '" width="100%" /></div>';
        html += '<div class="diva2n"><p class="tx3">&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;<strong style="color:#88abda">' + escapeAboutHtml(item.name) + '</strong>&nbsp;' + escapeAboutHtml(item.description) + '<br/>';

        for (j = 0; j < item.tags.length; j++) {
            html += '[' + escapeAboutHtml(item.tags[j]) + ']';
        }

        html += '</p></div></div></a><div style="clear:both;">&nbsp;</div>';
    }

    container.innerHTML = html;
}

function renderAboutTeamMembers(selector) {
    var container = document.querySelector(selector);
    var html = "";
    var i;
    var member;
    var j;

    if (!container) {
        return;
    }

    for (i = 0; i < aboutTeamMembers.length; i++) {
        member = aboutTeamMembers[i];
        html += '<div style="clear:both">';
        html += '<br/><br/>';

        if (member.profileHref) {
            html += '<a href="' + escapeAboutHtml(member.profileHref) + '" target="_blank"><div class="diva1n tx2">' + escapeAboutHtml(member.name) + '</div></a>';
        } else {
            html += '<div class="diva1n tx2">' + escapeAboutHtml(member.name) + '</div>';
        }

        html += '<div class="diva2n tx3">';
        for (j = 0; j < member.paragraphs.length; j++) {
            if (j > 0) {
                html += '<br/><br/>';
            }
            html += escapeAboutHtml(member.paragraphs[j]);
        }
        html += '</div></div>';
    }

    html += '<div style="clear:both;">&nbsp;</div>';
    container.innerHTML = html;
}
